import {
  ApiKeyAdminSchema,
  GraphSchema,
  ItemPageSchema,
  NeighborhoodSchema,
  DeleteResultSchema,
  ObservationDetailSchema,
  ObservationPageSchema,
  ProblemContextSchema,
  ProblemDetailSchema,
  ProblemPageSchema,
  SearchPageSchema,
  SolutionSchema,
  WorkspaceSummarySchema,
  z,
  type CreateSolution,
  type Graph,
  type ItemPage,
  type Neighborhood,
  type ObservationDetail,
  type ObservationPage,
  type ProblemContext,
  type ProblemDetail,
  type ProblemPage,
  type SearchPage,
  type Solution,
  type UpdateObservation,
  type UpdateProblem,
  type UpdateSolution,
  type ApiKeyAdmin,
  type WorkspaceSummary,
} from "../lib/contract/index.js";
import createClient from "openapi-fetch";
import { config } from "./config.js";
import type { paths } from "./api-types.js";

/**
 * End-to-end typed client. Paths, methods, params and request bodies are
 * inferred from `paths`, generated by `openapi-typescript` from the committed
 * `openapi.json` (run `bun run webpoc:gen:api` after a contract change).
 * The web app depends only on that spec — not on the API's source types.
 *
 * Responses are additionally validated at runtime against the shared
 * `lib/contract` Zod schemas, so a server that drifts from the contract is
 * caught here instead of corrupting the UI with an unexpected shape.
 *
 * Auth is the Better Auth session cookie — `credentials: "include"` sends it
 * with every `/v1/*` request (same-origin via the Vite proxy in dev). The active
 * workspace is resolved server-side from the session, so requests carry no
 * tenant id.
 */
const client = createClient<paths>({
  baseUrl: config.apiUrl,
  credentials: "include",
});

function unwrap<T>(
  schema: z.ZodType<T>,
  result: { data?: unknown; error?: unknown; response: Response },
): T {
  if (result.data == null) throw new Error(`Request failed: ${result.response.status}`);
  return schema.parse(result.data);
}

export const api = {
  /* ---- Observations ---- */
  async listObservations(params: {
    q?: string;
    tag?: string;
    status?: "open" | "synthesized" | "archived";
    solved?: boolean;
    workspaceId?: string;
    limit?: number;
    offset?: number;
  } = {}): Promise<ObservationPage> {
    return unwrap(ObservationPageSchema, await client.GET("/v1/observations", { params: { query: params } }));
  },

  async getObservation(id: string): Promise<ObservationDetail> {
    return unwrap(ObservationDetailSchema, await client.GET("/v1/observations/{id}", {
      params: { path: { id } },
    }));
  },

  async updateObservation(id: string, patch: UpdateObservation): Promise<ObservationDetail> {
    return unwrap(ObservationDetailSchema, await client.PATCH("/v1/observations/{id}", {
      params: { path: { id } },
      body: patch,
    }));
  },

  async deleteObservation(id: string): Promise<void> {
    const res = await client.DELETE("/v1/observations/{id}", { params: { path: { id } } });
    if (res.error) throw new Error(`Request failed: ${res.response.status}`);
    DeleteResultSchema.parse(res.data);
  },

  /** Every observation that names this source. */
  async listSourceObservations(id: string): Promise<ObservationPage> {
    return unwrap(ObservationPageSchema, await client.GET("/v1/sources/{id}/observations", {
      params: { path: { id }, query: {} },
    }));
  },

  /* ---- Problems ---- */
  async listProblems(params: {
    q?: string;
    tag?: string;
    solved?: boolean;
    workspaceId?: string;
    limit?: number;
    offset?: number;
  } = {}): Promise<ProblemPage> {
    return unwrap(ProblemPageSchema, await client.GET("/v1/problems", { params: { query: params } }));
  },

  /* ---- Unified feed (observations + problems, one createdAt order) ---- */
  async listItems(params: {
    q?: string;
    tag?: string;
    solved?: boolean;
    workspaceId?: string;
    type?: "all" | "observations" | "problems";
    limit?: number;
    offset?: number;
  } = {}): Promise<ItemPage> {
    return unwrap(ItemPageSchema, await client.GET("/v1/items", { params: { query: params } }));
  },

  async getProblem(id: string): Promise<ProblemDetail> {
    return unwrap(ProblemDetailSchema, await client.GET("/v1/problems/{id}", {
      params: { path: { id } },
    }));
  },

  async updateProblem(id: string, patch: UpdateProblem): Promise<ProblemDetail> {
    return unwrap(ProblemDetailSchema, await client.PATCH("/v1/problems/{id}", {
      params: { path: { id } },
      body: patch,
    }));
  },

  async deleteProblem(id: string): Promise<void> {
    const res = await client.DELETE("/v1/problems/{id}", { params: { path: { id } } });
    if (res.error) throw new Error(`Request failed: ${res.response.status}`);
    DeleteResultSchema.parse(res.data);
  },

  /* ---- Search (D1 FTS5, ranked, snippets) ---- */
  /** Ranked hits across observations and problems. The one text search there is. */
  async search(params: { q: string; limit?: number; offset?: number }): Promise<SearchPage> {
    return unwrap(SearchPageSchema, await client.GET("/v1/search", { params: { query: params } }));
  },

  /* ---- Solutions (polymorphic) ---- */
  async listSolutions(targetKind: "observation" | "problem", targetId: string): Promise<Solution[]> {
    return unwrap(z.array(SolutionSchema), await client.GET("/v1/solutions", {
      params: { query: { targetKind, targetId } },
    }));
  },

  /** Attach a human-authored solution to an observation or problem. */
  async createSolution(input: Omit<CreateSolution, "origin">): Promise<Solution> {
    return unwrap(SolutionSchema, await client.POST("/v1/solutions", {
      body: { ...input, origin: "human" },
    }));
  },

  async updateSolution(id: string, patch: UpdateSolution): Promise<Solution> {
    return unwrap(SolutionSchema, await client.PATCH("/v1/solutions/{id}", {
      params: { path: { id } },
      body: patch,
    }));
  },

  /* ---- Graph + meta ---- */
  async getGraph(workspaceId?: string): Promise<Graph> {
    return unwrap(GraphSchema, await client.GET("/v1/graph", { params: { query: { workspaceId } } }));
  },

  async getNeighborhood(id: string): Promise<Neighborhood> {
    return unwrap(NeighborhoodSchema, await client.GET("/v1/problems/{id}/neighborhood", {
      params: { path: { id }, query: {} },
    }));
  },

  async getProblemContext(id: string): Promise<ProblemContext> {
    return unwrap(ProblemContextSchema, await client.GET("/v1/problems/{id}/context", {
      params: { path: { id } },
    }));
  },

  /* ---- Workspaces ---- */
  /** Every workspace the caller can access (for the picker + list filters). */
  async listWorkspaces(): Promise<WorkspaceSummary[]> {
    return unwrap(z.array(WorkspaceSummarySchema), await client.GET("/v1/workspaces"));
  },

  /** Make a workspace active, auto-enrolling membership so the switch succeeds. */
  async activateWorkspace(id: string): Promise<WorkspaceSummary> {
    return unwrap(WorkspaceSummarySchema, await client.POST("/v1/workspaces/{id}/activate", {
      params: { path: { id } },
    }));
  },

  /* ---- API keys (shared registry; any user sees/revokes any key) ---- */
  /** Every API key, with its owner and last-used time (no secret). */
  async listApiKeys(): Promise<ApiKeyAdmin[]> {
    return unwrap(z.array(ApiKeyAdminSchema), await client.GET("/v1/api-keys"));
  },

  /** Revoke any key by id. */
  async revokeApiKey(id: string): Promise<void> {
    const res = await client.DELETE("/v1/api-keys/{id}", { params: { path: { id } } });
    if (res.error) throw new Error(`Request failed: ${res.response.status}`);
  },
};
