// The BaseManifest generator (ADR-0022 decision 8, #363). The platform Component tier is
// image-only — neither Record nor File — so the edge cannot read it: it is deploy-gated code,
// identical across workspaces, versioned with the image that expects it. This walks that
// directory at BUILD time and emits the names and descriptions the edge needs to answer
// `list_components` for the base tier without waking a container.
//
// The output is COMMITTED (`worker/base-manifest.generated.ts`), which is the second reason
// this exists: adding or removing a platform Component becomes a line in a pull request
// instead of an invisible filesystem fact (PRD #354 story 28). `worker/base-manifest.test.ts`
// regenerates and compares, so a committed copy cannot quietly rot.
//
// Run it with `bun run gen:base-manifest`; `bun run build` runs it first, so a deploy always
// bundles a manifest generated from the image it is shipping.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { leadingComment } from '../shared/component-description.ts';

/** The platform tier (ADR-0014): `src/canvas-components/`, read-only at runtime. */
const BASE_DIR = fileURLToPath(new URL('../src/canvas-components/', import.meta.url));
const OUT = fileURLToPath(new URL('../worker/base-manifest.generated.ts', import.meta.url));

export type BaseComponent = { name: string; description: string };

/**
 * Every platform Component, by name, with its description — the same `.tsx`-only rule and the
 * same leading-comment extraction the container's own listing uses, so the edge's base tier
 * and the container's cannot disagree about what is in the image.
 */
export function platformTierManifest(dir: string = BASE_DIR): BaseComponent[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.tsx'))
    .map((f) => f.replace(/\.tsx$/, ''))
    .sort()
    .map((name) => ({ name, description: leadingComment(readFileSync(`${dir}${name}.tsx`, 'utf8')) }));
}

/** The committed module's text. Kept next to the generator so the header explaining what
 *  regenerates the file lives with the code that writes it. */
export function renderManifest(entries: BaseComponent[]): string {
  return [
    '// GENERATED by `bun run gen:base-manifest` — do not edit by hand.',
    '//',
    '// The platform Component tier (ADR-0022 decision 8) is image-only, so the edge cannot read',
    '// it off a filesystem. This is what the edge knows the base tier by, bundled with the',
    '// worker; `worker/base-manifest.test.ts` fails if it drifts from `src/canvas-components/`.',
    'export const BASE_COMPONENTS: ReadonlyArray<{ name: string; description: string }> = [',
    ...entries.map((e) => `  { name: ${JSON.stringify(e.name)}, description: ${JSON.stringify(e.description)} },`),
    '];',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const entries = platformTierManifest();
  writeFileSync(OUT, renderManifest(entries));
  console.log(`[base-manifest] ${entries.length} platform components → worker/base-manifest.generated.ts`);
}
